import runpy, pathlib
H = pathlib.Path(__file__).parent
UI = runpy.run_path(str(H/'dict_ui.py'))['UI']
R = runpy.run_path(str(H/'dict_radio.py'))
def k(s): return '"' + s.replace('\\','\\\\').replace('"','\\"').replace('$','\\$').replace('\n','\\n') + '"'
en = {}; br = {}
for pt,(e,b) in UI.items():
    en[pt]=e
    if b: br[pt]=b
for pt,e in R['COUNTRIES'].items(): en[pt]=e
for pt,b in R['COUNTRIES_BR'].items(): br[pt]=b
for pt,e in R['RADIO'].items(): en[pt]=e
for pt,e in runpy.run_path(str(H/'dict_titles.py'))['TITLES'].items(): en[pt]=e
out = ["// Generated by companion/i18n/gerar_kotlin.py — do not edit by hand.", "package com.oracleos.app.ui", "",
       "internal val EN_EXACT: Map<String, String> = hashMapOf("]
out += [f"    {k(a.lower())} to {k(b)}," for a,b in en.items()]
out += [")", "", "internal val BR_EXACT: Map<String, String> = hashMapOf("]
out += [f"    {k(a.lower())} to {k(b)}," for a,b in br.items()]
out += [")", "", "internal val EN_FRAGMENTS: List<Pair<String, String>> = listOf("]
out += [f"    {k(a)} to {k(b)}," for a,b in R['FRAGMENTS']]
out += [")", ""]
dest = H.parents[1]/'app/src/main/java/com/oracleos/app/ui/I18nStrings.kt'
dest.write_text("\n".join(out), encoding='utf-8')
print(len(en), len(br), dest)
